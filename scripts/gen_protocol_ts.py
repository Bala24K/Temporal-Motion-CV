"""Generate web/lib/protocol.ts from backend/protocol.py (the live WebSocket protocol).

    python scripts/gen_protocol_ts.py          # write
    python scripts/gen_protocol_ts.py --check  # exit 1 if the file is out of date (CI / tests)

No new dependency: pydantic's JSON Schema is translated to TypeScript for the small set of constructs the protocol
uses (objects, literals, unions/optionals, arrays, string-keyed maps, nested models).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.protocol import CLIENT_MODELS, PROTOCOL_VERSION, SERVER_MODELS  # noqa: E402

OUT = ROOT / "web" / "lib" / "protocol.ts"


def ts_type(s: dict, defs: dict) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return repr(s["const"]).replace("'", '"') if isinstance(s["const"], str) else str(s["const"]).lower()
    if "enum" in s:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in s["enum"])
    if "anyOf" in s:
        parts = []
        for x in s["anyOf"]:
            t = ts_type(x, defs)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    t = s.get("type")
    if t == "array":
        inner = ts_type(s.get("items", {}), defs)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {ts_type(ap, defs)}>"
        return "Record<string, unknown>"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def interface(name: str, s: dict, defs: dict) -> str:
    req = set(s.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, ps in s.get("properties", {}).items():
        opt = "" if prop in req else "?"
        lines.append(f"  {prop}{opt}: {ts_type(ps, defs)};")
    lines.append("}")
    return "\n".join(lines)


def generate() -> str:
    blocks, seen = [], set()
    for group in (CLIENT_MODELS, SERVER_MODELS):
        for m in group:
            sch = m.model_json_schema(ref_template="#/$defs/{model}")
            defs = sch.get("$defs", {})
            for dn, ds in defs.items():
                if dn not in seen:
                    seen.add(dn)
                    blocks.append(interface(dn, ds, defs))
            if m.__name__ not in seen:
                seen.add(m.__name__)
                blocks.append(interface(m.__name__, sch, defs))
    head = ("// GENERATED by scripts/gen_protocol_ts.py from backend/protocol.py - do not edit by hand.\n"
            "// Regenerate: python scripts/gen_protocol_ts.py\n\n"
            f"export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n\n")
    unions = (f"\nexport type ClientMessage = {' | '.join(m.__name__ for m in CLIENT_MODELS)};\n"
              f"export type ServerMessage = {' | '.join(m.__name__ for m in SERVER_MODELS)};\n")
    return head + "\n\n".join(blocks) + "\n" + unions


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("web/lib/protocol.ts is out of date: run python scripts/gen_protocol_ts.py", file=sys.stderr)
            sys.exit(1)
        print("protocol.ts up to date")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")
