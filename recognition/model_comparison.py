"""
Multi-model comparison on the structured/temporal skeleton representation
(V1 §15's own suggested experiment: try several models and measure which
learns best, rather than assuming Random Forest is the final answer).

ALL models are trained and evaluated on SYNTHETIC data generated by
pose_sequence_synthesis.py — see that module's and
recognition/dataset_synthesis.py's docstrings for exactly what that does
and doesn't validate. This answers "which model learns best from this
representation, on this synthetic data" — it does NOT answer "which
model will perform best on real video," which needs real data (see
STATUS.md).
"""
from dataclasses import dataclass
from typing import Dict
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.model_selection import GroupShuffleSplit
from sklearn.preprocessing import LabelEncoder, StandardScaler
from xgboost import XGBClassifier

from recognition.skeleton_dataset import generate_engineered_dataset, generate_sequence_dataset
from recognition.temporal_model import TemporalCNNClassifier
from recognition.dataset_synthesis import EXERCISES
from evaluation.classification import classification_report, ClassificationReport


@dataclass
class ModelResult:
    name: str
    report: ClassificationReport
    n_train: int
    n_test: int


def _split_indices(subject_ids: np.ndarray, test_size: float = 0.25, seed: int = 0):
    splitter = GroupShuffleSplit(n_splits=1, test_size=test_size, random_state=seed)
    return next(splitter.split(np.zeros(len(subject_ids)), groups=subject_ids))


def run_comparison(n_subjects: int = 30, windows_per_subject_per_exercise: int = 15,
                    n_frames: int = 16, seed: int = 0, cnn_epochs: int = 40) -> Dict[str, ModelResult]:
    X_eng, y_eng, subj = generate_engineered_dataset(n_subjects, windows_per_subject_per_exercise, n_frames, seed)
    X_seq, y_seq, subj_seq = generate_sequence_dataset(n_subjects, windows_per_subject_per_exercise, n_frames, seed)
    assert np.array_equal(subj, subj_seq) and np.array_equal(y_eng, y_seq), \
        "engineered/sequence datasets must be paired for a fair comparison"

    train_idx, test_idx = _split_indices(subj, seed=seed)
    results: Dict[str, ModelResult] = {}

    sklearn_models = [
        ("random_forest", RandomForestClassifier(n_estimators=200, max_depth=8, random_state=seed)),
    ]
    for name, model in sklearn_models:
        model.fit(X_eng[train_idx], y_eng[train_idx])
        y_pred = model.predict(X_eng[test_idx])
        results[name] = ModelResult(name, classification_report(y_eng[test_idx], y_pred, labels=EXERCISES),
                                     n_train=len(train_idx), n_test=len(test_idx))

    # MLP, UNLIKE the tree-based models above, needs scaled input features
    # to train well — trees split on threshold comparisons per feature so
    # scale doesn't matter, but a neural net's gradient-based optimization
    # is sensitive to it. Found during development: the MLP scored only
    # 67% accuracy on raw features vs. 97-100% for everything else, which
    # turned out to be exactly this, confirmed by testing with and without
    # a StandardScaler — not a real weakness of MLPs on this data.
    scaler = StandardScaler().fit(X_eng[train_idx])
    mlp = MLPClassifier(hidden_layer_sizes=(32, 16), max_iter=500, random_state=seed)
    mlp.fit(scaler.transform(X_eng[train_idx]), y_eng[train_idx])
    y_pred_mlp = mlp.predict(scaler.transform(X_eng[test_idx]))
    results["mlp"] = ModelResult("mlp", classification_report(y_eng[test_idx], y_pred_mlp, labels=EXERCISES),
                                  n_train=len(train_idx), n_test=len(test_idx))

    # XGBoost's sklearn API wants integer-encoded labels, not strings.
    label_encoder = LabelEncoder().fit(EXERCISES)
    xgb = XGBClassifier(n_estimators=200, max_depth=4, random_state=seed, eval_metric="mlogloss", verbosity=0)
    xgb.fit(X_eng[train_idx], label_encoder.transform(y_eng[train_idx]))
    y_pred_xgb = label_encoder.inverse_transform(xgb.predict(X_eng[test_idx]))
    results["xgboost"] = ModelResult("xgboost", classification_report(y_eng[test_idx], y_pred_xgb, labels=EXERCISES),
                                      n_train=len(train_idx), n_test=len(test_idx))

    cnn = TemporalCNNClassifier(epochs=cnn_epochs, seed=seed)
    cnn.fit(X_seq[train_idx], y_seq[train_idx])
    y_pred_cnn = cnn.predict(X_seq[test_idx])
    results["temporal_cnn"] = ModelResult(
        "temporal_cnn", classification_report(y_seq[test_idx], y_pred_cnn, labels=EXERCISES),
        n_train=len(train_idx), n_test=len(test_idx),
    )

    return results
