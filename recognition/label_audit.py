"""
Label Quality & Threshold Ambiguity Audit for QEVD Pose Sequences.

Audits heuristic rule-based labels generated by movement kinematics:
  - Class distribution per decision rule
  - Count and fraction of fallback 'lateral_raise' clips
  - Kinematic measurement distributions (knee_rom, wrist_above_ratio, elbow_rom)
  - Identifies and flags ambiguous clips close to decision boundaries
  - Exports ambiguous video IDs to analysis/ambiguous_qevd_clips.json
"""

import json
import os
from typing import Dict, List, Tuple
import numpy as np

from body_model.skeleton import SkeletonFrame
from body_model.sequence import SkeletonSequence
from recognition.qevd_dataset import load_or_build_pose_cache, EXERCISES


def analyze_clip_kinematics(pose_frames: List) -> Dict[str, float]:
    """Computes key kinematic measurements for a single video sequence."""
    skel_seq = SkeletonSequence()
    for pf in pose_frames:
        sf = SkeletonFrame.from_pose_frame(pf)
        skel_seq.push(sf)

    # 1. Elbow ROM
    left_elbow = [f.joint_angles.get("left_elbow") for f in skel_seq.frames if f.joint_angles.get("left_elbow") is not None]
    right_elbow = [f.joint_angles.get("right_elbow") for f in skel_seq.frames if f.joint_angles.get("right_elbow") is not None]
    elbow_rom = 0.0
    if left_elbow:
        elbow_rom = max(elbow_rom, max(left_elbow) - min(left_elbow))
    if right_elbow:
        elbow_rom = max(elbow_rom, max(right_elbow) - min(right_elbow))

    # 2. Knee ROM
    left_knee = [f.joint_angles.get("left_knee") for f in skel_seq.frames if f.joint_angles.get("left_knee") is not None]
    right_knee = [f.joint_angles.get("right_knee") for f in skel_seq.frames if f.joint_angles.get("right_knee") is not None]
    knee_rom = 0.0
    if left_knee:
        knee_rom = max(knee_rom, max(left_knee) - min(left_knee))
    if right_knee:
        knee_rom = max(knee_rom, max(right_knee) - min(right_knee))

    # 3. Wrist above shoulder ratio
    wrist_above_count = 0
    total_valid = 0
    for pf in pose_frames:
        lw, rw = pf.get("left_wrist"), pf.get("right_wrist")
        ls, rs = pf.get("left_shoulder"), pf.get("right_shoulder")
        if lw and ls:
            total_valid += 1
            if lw.y < ls.y:
                wrist_above_count += 1
        if rw and rs:
            total_valid += 1
            if rw.y < rs.y:
                wrist_above_count += 1

    wrist_ratio = (wrist_above_count / max(1, total_valid)) if total_valid > 0 else 0.0

    return {
        "knee_rom": float(knee_rom),
        "elbow_rom": float(elbow_rom),
        "wrist_above_ratio": float(wrist_ratio),
    }


def audit_label_quality(cache: Dict[str, Dict], output_path: str = "analysis/ambiguous_qevd_clips.json") -> Dict:
    """
    Scans pose cache and evaluates heuristic label decision boundaries:
      - knee_rom boundary: 20.0° (ambiguity band: 15.0° - 25.0°)
      - wrist_above_ratio boundary: 0.20 (ambiguity band: 0.15 - 0.25)
      - elbow_rom boundary: 25.0° (ambiguity band: 20.0° - 30.0°)
    """
    rule_counts = {ex: 0 for ex in EXERCISES}
    ambiguous_clips = []
    kinematic_stats = {ex: {"knee_rom": [], "elbow_rom": [], "wrist_ratio": []} for ex in EXERCISES}

    for vid, item in cache.items():
        pose_frames = item["pose_frames"]
        label = item["label"]
        rule_counts[label] = rule_counts.get(label, 0) + 1

        kin = analyze_clip_kinematics(pose_frames)
        kinematic_stats[label]["knee_rom"].append(kin["knee_rom"])
        kinematic_stats[label]["elbow_rom"].append(kin["elbow_rom"])
        kinematic_stats[label]["wrist_ratio"].append(kin["wrist_above_ratio"])

        # Check proximity to decision boundaries
        is_ambiguous = False
        reasons = []

        if 15.0 <= kin["knee_rom"] <= 25.0:
            is_ambiguous = True
            reasons.append(f"knee_rom {kin['knee_rom']:.1f}° near 20.0° squat threshold")

        if 0.15 <= kin["wrist_above_ratio"] <= 0.25:
            is_ambiguous = True
            reasons.append(f"wrist_ratio {kin['wrist_above_ratio']:.2f} near 0.20 press threshold")

        if 20.0 <= kin["elbow_rom"] <= 30.0:
            is_ambiguous = True
            reasons.append(f"elbow_rom {kin['elbow_rom']:.1f}° near 25.0° curl threshold")

        if is_ambiguous:
            ambiguous_clips.append({
                "video_id": vid,
                "assigned_label": label,
                "kinematics": kin,
                "ambiguity_reasons": reasons,
            })

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        json.dump({
            "total_audited_videos": len(cache),
            "rule_counts": rule_counts,
            "fallback_lateral_raise_count": rule_counts.get("lateral_raise", 0),
            "fallback_lateral_raise_ratio": float(rule_counts.get("lateral_raise", 0) / max(1, len(cache))),
            "ambiguous_clip_count": len(ambiguous_clips),
            "ambiguous_clips": ambiguous_clips,
        }, f, indent=2)

    return {
        "total_audited_videos": len(cache),
        "rule_counts": rule_counts,
        "ambiguous_count": len(ambiguous_clips),
        "ambiguous_clips": ambiguous_clips,
        "output_path": output_path,
    }


def main():
    print("Running QEVD Label Quality & Ambiguity Audit...")
    cache = load_or_build_pose_cache(target_per_class=25)
    res = audit_label_quality(cache)
    print(f"Audited {res['total_audited_videos']} clips.")
    print(f"Rule distribution: {res['rule_counts']}")
    print(f"Ambiguous clips near decision thresholds: {res['ambiguous_count']}")
    print(f"Saved ambiguity report to {res['output_path']}")


if __name__ == "__main__":
    main()
